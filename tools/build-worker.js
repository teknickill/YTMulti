// Builds worker/worker.js: one file you can paste into the Cloudflare
// dashboard. It's public/ytcore.js (the shared YouTube parser) + worker/handler.js.
//   npm run build:worker
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const core = fs.readFileSync(path.join(root, "public", "ytcore.js"), "utf8");
// The Node-only export line isn't needed (and wrangler warns about it) in a Worker.
const NODE_EXPORT = '  if (typeof module === "object" && module.exports) module.exports = YTCore;\n';
if (core.split(NODE_EXPORT).length !== 2) throw new Error("ytcore.js export line not found exactly once");
const handler = fs.readFileSync(path.join(root, "worker", "handler.js"), "utf8");
const out = "// GENERATED by `npm run build:worker` from public/ytcore.js + worker/handler.js.\n" +
  "// Edit those files, not this one.\n\n" + core.replace(NODE_EXPORT, "") + "\n" + handler;
fs.writeFileSync(path.join(root, "worker", "worker.js"), out);
console.log(`worker/worker.js written (${(out.length / 1024).toFixed(1)} KB)`);
